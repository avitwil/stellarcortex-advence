#!/usr/bin/env node
// NFR-LIC-01 / NFR-COST-01: every bundled production dependency must have a license that
// allows private redistribution, and none may be GPL/AGPL. Regenerates the bundled-deps
// table in THIRD_PARTY_NOTICES.md (use --write) and fails if it is out of date.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';

const ALLOWED = new Set(['MIT', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', 'Apache-2.0', '0BSD', 'BlueOak-1.0.0', 'MPL-2.0', 'CC0-1.0', 'Unlicense', 'Python-2.0', 'CC-BY-4.0', 'Zlib']);
const FORBIDDEN = /\b(A?GPL|LGPL|SSPL|BUSL|Commons-Clause|EUPL|CPAL|OSL)\b/i;

function ok(expr) {
  if (FORBIDDEN.test(expr)) {
    // "(MIT OR GPL-2.0)" is fine: we choose the permissive option.
    const opts = expr.replace(/[()]/g, '').split(/\s+OR\s+/i);
    return opts.some((o) => ALLOWED.has(o.trim()));
  }
  const opts = expr.replace(/[()]/g, '').split(/\s+OR\s+/i);
  if (opts.some((o) => ALLOWED.has(o.trim()))) return true;
  const ands = expr.replace(/[()]/g, '').split(/\s+AND\s+/i);
  return ands.every((a) => ALLOWED.has(a.trim()));
}

const raw = execFileSync('pnpm', ['licenses', 'list', '--prod', '--json'], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
const data = JSON.parse(raw);
const rows = [];
const bad = [];
for (const [lic, pkgs] of Object.entries(data)) {
  for (const p of pkgs) {
    if (p.name.startsWith('@advence/')) continue;
    for (const v of p.versions) rows.push({ name: p.name, version: v, license: lic });
    if (!ok(lic)) bad.push(`${p.name}@${p.versions.join(',')}: ${lic}`);
  }
}
rows.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const table = ['| Package | Version | License |', '|---|---|---|', ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`)].join('\n') + '\n';
const MARK = '<!-- generated by scripts/check-licenses.mjs; do not edit below this line -->';
const notices = fs.readFileSync('THIRD_PARTY_NOTICES.md', 'utf8');
const head = notices.split(MARK)[0];
const next = `${head}${MARK}\n${table}`;
if (process.argv.includes('--write')) fs.writeFileSync('THIRD_PARTY_NOTICES.md', next);
let failed = false;
if (bad.length) {
  console.error('License check failed, not allowed:\n' + bad.join('\n'));
  failed = true;
}
if (!process.argv.includes('--write') && next !== notices) {
  console.error('THIRD_PARTY_NOTICES.md is out of date; run `node scripts/check-licenses.mjs --write`.');
  failed = true;
}
if (failed) process.exit(1);
console.log(`License check passed: ${rows.length} bundled package versions, all allowed and listed.`);
